'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'solver-worker-client.js');
const sources = [
  'cube-model.js',
  'solver-engine.js',
  'two-solver.js',
  'two-optimal-solver.js',
  'vendor/nxn-solver/solver.js',
  'layer-solver.js',
  'vendor/cubejs/cube.js',
  'vendor/cubejs/solve.js',
  'short-solver.js',
  'vendor/four-solver/solver.js',
  'four-solver.js',
  'solver-worker.js'
];
const licenses = ['vendor/cubejs/LICENSE', 'vendor/nxn-solver/LICENSE', 'vendor/four-solver/LICENSE'];

function renderBundle() {
  const notices = licenses.map(file =>
    `/* ${file}\n\n${fs.readFileSync(path.join(root, file), 'utf8').trimEnd()}\n*/`).join('\n\n');
  const body = sources.map(file =>
    `// Source: ${file}\n${fs.readFileSync(path.join(root, file), 'utf8').replace(/^[ \t]+$/gm, '').trimEnd()}\n;`).join('\n\n');

  // Keep workerMain outside strict mode: cubejs publishes its exports using `this`.
  // Its body is serialized, so solver code never runs in the page's JS context.
  return `// Generated by node scripts/build-worker.cjs; do not edit directly.
// Contains every worker dependency so HTTP and file:// use the same solver code.

${notices}

(function (root) {
  function workerMain() {
${body}
  }

  function create() {
    var source = '(' + workerMain.toString() + ')();';
    var blob = new root.Blob([source], { type: 'text/javascript' });
    var url = root.URL.createObjectURL(blob);
    try {
      return new root.Worker(url);
    } finally {
      root.URL.revokeObjectURL(url);
    }
  }

  root.CubeSolverWorker = { create: create };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

function main(args) {
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: node scripts/build-worker.cjs [--check]');
  }
  const generated = renderBundle();
  if (args[0] === '--check') {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
      throw new Error('solver-worker-client.js is stale. Run node scripts/build-worker.cjs.');
    }
    console.log('Worker bundle matches its source files.');
  } else {
    fs.writeFileSync(output, generated);
    console.log('Wrote solver-worker-client.js.');
  }
}

if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { renderBundle, sources, licenses };
